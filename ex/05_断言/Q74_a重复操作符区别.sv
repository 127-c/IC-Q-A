//=============================================================
// Q74_练习：SVA 重复操作符 a[*3] / a[->3] / a[=3] 的区别
// 难度: ⭐⭐ | 目标: 掌握三种重复操作符的语义
//=============================================================

module tb_q74_repeat;
  bit clk, a, b, c;
  always #5 clk = ~clk;


  //----------------------------------------------------------
  // TODO 1: a[*3] — 连续重复3次, 中间不能有间断
  //   等价于: a ##1 a ##1 a
  //   使用场景: burst连续3拍有效的检测
  //----------------------------------------------------------
  property p_consecutive;
    @(posedge clk)
      a[*3] |-> c;   // a连续3周期为高后, c为高
  endproperty


  //----------------------------------------------------------
  // TODO 2: a[->3] — 非连续重复3次, 最后一次匹配后紧跟后续
  //   等价于: (!a[*0:$] ##1 a)[*3] (goto repetition)
  //   使用场景: 第三次握手后立即响应
  //----------------------------------------------------------
  property p_goto;
    @(posedge clk)
      a[->3] |-> c;  // a第3次为高后, 下一拍c为高 (紧跟!)
  endproperty


  //----------------------------------------------------------
  // TODO 3: a[=3] — 非连续重复3次, 最后一次匹配后可以有间隔
  //   等价于: (!a[*0:$] ##1 a)[*3] ##1 !a[*0:$]
  //   使用场景: 第三次出现后, 某时刻c响应(不必紧跟)
  //----------------------------------------------------------
  property p_nonconsecutive;
    @(posedge clk)
      a[=3] |-> c;   // a第3次为高后, 某个时刻c为高 (可有间隔)
  endproperty


  //----------------------------------------------------------
  // 测试: 画出时序图理解
  // clk: _/⁠\\_/\\_/\\_/\\_/\\_/\\_/\\_/\\_/\\_
  // a:    0 1  0 1  1  0  1  0  1  0
  //       T1   T3  T5     T7    T9
  //
  // a[*3]  : 需要连续3个1 (此处没有)
  // a[->3] : 第3次a=1在T5, T6时需c=1
  // a[=3]  : 第3次a=1在T5, 之后某时刻c=1即可
  //----------------------------------------------------------

  initial begin
    a=0; c=0;
    #10;
    @(posedge clk); a=1;    // T1
    @(posedge clk); a=0;    // T2
    @(posedge clk); a=1;    // T3
    @(posedge clk); a=0;    // T4
    @(posedge clk); a=1; c=1; // T5: a=1(第3次), c=1
    @(posedge clk); a=0; c=0; // T6
    @(posedge clk); a=0;    // T7
    #30; $finish;
  end

endmodule
